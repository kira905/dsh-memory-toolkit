/**
* Render one memory as a prompt line.
* @param record - the memory to render.
* @returns a single line carrying the id, tags, and text.
*/
function promptLine(record) {
	const tags = record.tags.length > 0 ? ` [${record.tags}]` : "";
	return `- (#${record.id}${record.pinned ? ", pinned" : ""})${tags} ${record.text}`;
}
/**
* Render the prompt section body under a character budget. Pinned memories are
* emitted first, so a budget too small for everything keeps what the deployment
* explicitly marked as always-relevant.
* @param records - pinned records followed by recent ones.
* @param maxChars - the budget.
* @returns the section text, or an empty string when nothing fits or nothing is stored.
*/
function renderPrompt(records, maxChars) {
	if (records.length === 0) return "";
	const header = "Memories you previously stored (use memory_search for anything not listed):\n";
	const lines = [];
	let used = 76;
	let dropped = 0;
	for (const record of records) {
		const line = promptLine(record);
		if (used + line.length + 1 > maxChars) {
			dropped++;
			continue;
		}
		lines.push(line);
		used += line.length + 1;
	}
	if (lines.length === 0) return "";
	const tail = dropped > 0 ? `\n(${dropped} more memories not shown; use memory_search)` : "";
	return header + lines.join("\n") + tail;
}
/**
* Validate the bounds the schema cannot express, so an unusable configuration
* fails at plugin load rather than at the first tool call.
* @param config - the schema-validated config.
* @throws when a bound is not a positive integer, or the default search limit exceeds its cap.
*/
function validateConfig(config) {
	const bounds = [
		["promptRecentCount", config.promptRecentCount],
		["promptMaxChars", config.promptMaxChars],
		["maxTextChars", config.maxTextChars],
		["searchLimitDefault", config.searchLimitDefault],
		["searchLimitMax", config.searchLimitMax]
	];
	for (const [field, value] of bounds) if (!Number.isInteger(value) || value < 1) throw new Error(`memory: invalid ${field} ${value} — must be an integer >= 1`);
	if (config.searchLimitDefault > config.searchLimitMax) throw new Error(`memory: searchLimitDefault ${config.searchLimitDefault} exceeds searchLimitMax ${config.searchLimitMax}`);
	if (config.path.length === 0) throw new Error("memory: `path` must not be empty");
	// FORK-EDIT(2026-09-21): 注入预算参数必须是正整数（误配在加载期就炸，不拖到第一个回合）
	const recallBounds = [
		["recallBridgePort", config.recallBridgePort],
		["recallBridgePortScanMax", config.recallBridgePortScanMax],
		["recallTimeoutMs", config.recallTimeoutMs],
		["recallEncodeTimeoutMs", config.recallEncodeTimeoutMs],
		["recallMaxItems", config.recallMaxItems],
		["recallMaxChars", config.recallMaxChars],
		["recallMaxTokens", config.recallMaxTokens],
		["recallMaxPerSession", config.recallMaxPerSession],
		["recallSummaryChars", config.recallSummaryChars],
		["recallQueryMaxChars", config.recallQueryMaxChars],
		["recallVectorTopK", config.recallVectorTopK],
		["recallFtsTopK", config.recallFtsTopK],
		["recallRrfK", config.recallRrfK],
		["recallResultTopK", config.recallResultTopK],
		["recallIndexTtlMs", config.recallIndexTtlMs]
	];
	for (const [field, value] of recallBounds) if (!Number.isInteger(value) || value < 1) throw new Error(`memory: invalid ${field} ${value} — must be an integer >= 1`);
	if (config.recallEncodeTimeoutMs > config.recallTimeoutMs) throw new Error(`memory: recallEncodeTimeoutMs ${config.recallEncodeTimeoutMs} must not exceed recallTimeoutMs ${config.recallTimeoutMs}`);
}
/**
 * FORK-EDIT(2026-09-21): 解析指针注入配置（记忆引擎 v2 §3.4）。
 * 路径一律按 `DSH_HOME` 解析（跨机/隔离实例口径：不写死机器名与盘符）；测试可全部覆盖。
 * 召回开关的**权威源 = 插件配置**（方案 §5.1 载体表），环境变量 `MEMORY_RECALL_ENABLED`
 * 只做**临时**覆盖（不落盘）。
 * @param {object} config - schema 校验后的配置。
 * @returns {object} 注入器配置。
 */
function resolveRecallConfig(config) {
	const home = config.recallHome || process.env.DSH_HOME || path.join(os.homedir(), ".dsh");
	const envFlag = process.env.MEMORY_RECALL_ENABLED;
	const envEnabled = envFlag === undefined ? null : /^(1|true|yes|on)$/i.test(String(envFlag));
	return {
		enabled: envEnabled === null ? Boolean(config.recallEnabled) : envEnabled,
		envOverride: envEnabled !== null,
		home,
		memoryDb: config.recallMemoryDb || config.path,
		vectorsDb: config.recallVectorsDb || path.join(home, "memory-vectors", "vectors.db"),
		logsDir: path.join(home, "logs"),
		bridgeHost: config.recallBridgeHost,
		bridgePort: config.recallBridgePort,
		bridgePortScanMax: config.recallBridgePortScanMax,
		timeoutMs: config.recallTimeoutMs,
		encodeTimeoutMs: config.recallEncodeTimeoutMs,
		maxItems: config.recallMaxItems,
		maxChars: config.recallMaxChars,
		maxTokens: config.recallMaxTokens,
		maxPerSession: config.recallMaxPerSession,
		summaryChars: config.recallSummaryChars,
		queryMaxChars: config.recallQueryMaxChars,
		vectorTopK: config.recallVectorTopK,
		ftsTopK: config.recallFtsTopK,
		rrfK: config.recallRrfK,
		resultTopK: config.recallResultTopK,
		indexTtlMs: config.recallIndexTtlMs
	};
}
/**
* Open the store, register the three tools, and contribute the recall section.
* @param ctx - plugin context; the store, tools, and section are disposed with it.
* @param config - validated {@link Config}.
*/
function apply(ctx, config) {
	validateConfig(config);
	/**
	* FORK-EDIT(2026-10-14): R1 解耦 —— 工具注册的唯一入口。
	* `defineTool` 来自顶层动态探测；不可用（主包删/改名该符号）⇒ **跳过注册**（插件降级、不崩 boot）。
	* 正常宿主下与 `ctx.tools.register(defineTool(def))` 逐点等价。
	* @param definition - defineTool 的入参。
	* @returns 是否真的注册了。
	*/
	const registerTool = (definition) => {
		if (typeof defineTool !== "function") return false;
		ctx.tools.register(defineTool(definition));
		return true;
	};
	// 主包可选依赖缺失时留一行可查痕迹（不抛、不阻断 apply）。
	if (HOST_OPTIONAL_LOAD_ERRORS.length > 0) {
		console.warn(`[memory] 主包可选依赖降级：${HOST_OPTIONAL_LOAD_ERRORS.join("；")}`);
	}
	// FORK-EDIT(2026-09-21): 指针注入接线（记忆引擎 v2 · S2b · 方案 §3.4/§6.1/§7）---------
	// 结构：logger（JSON 行 + 轮转 3×30 天）→ moduleGate（L2 模块位自我 drain）→ injector（编排）
	const recallConfig = resolveRecallConfig(config);
	const recallLogger = createRecallLogger({ dir: recallConfig.logsDir });
	const moduleGate = createModuleGate({ home: recallConfig.home });
	const injector = createRecallInjector({ config: recallConfig, logger: recallLogger, moduleGate });
	ctx.effect(() => () => {
		injector.close();
		recallLogger.sweep();
	}, "dsh-memory-local.injector");
	// FORK-EDIT(2026-09-21): 启动后预热（后台、非阻塞）——把向量矩阵与桥探活成本挪出首个回合，
	// 免得上线后第一次注入就顶破 300 ms 预算（真机实测踩过 524 ms 的那一次）。
	if (recallConfig.enabled) {
		const timer = setTimeout(() => {
			injector.warmup().then((r) => {
				if (!r.ok) recallLogger.log({ event: "warmup", ok: false, reason: r.reason });
			}).catch(() => {});
		}, 2000);
		if (typeof timer.unref === "function") timer.unref();
	}
	let store;
	ctx.effect(() => {
		store = new MemoryStore(config.path);
		return () => {
			store?.close();
			store = void 0;
		};
	});
	/**
	* The open store, or a loud failure. Reached only while the fiber is active,
	* so an absent store is a lifecycle bug rather than an expected state.
	* @returns the live store.
	*/
	function open() {
		if (!store) throw new Error("memory: store is not open");
		return store;
	}
	// FORK-EDIT(2026-10-16): `memory:recall` 段「会话内冻结」（harness 成本与路由线 · 主人拍板 ㈡档）。
	//
	// 为什么：下面这段 text() 在**每个 model step** 的 assemble 里都会被调用（宿主
	// `dsh-agent-loop` → `systemPrompt.assemble(assembleContextFor(agent, signal))`，该 context
	// 带 `{ agent, scope, signal }`），而它的内容是「最近 N 条记忆」—— 本会话里写一条记忆，
	// 这一段就变一次，**前缀缓存从这一段起全部失效**。冻结 = 同一会话内渲染一次后复用，
	// 缓存只在**新会话**第一轮重建。
	//
	// 保留（本次**不动**）：紧随其后的 `agent/pre-step` 指针注入 —— 它 append 在 messages
	// 尾部，本来就缓存友好（上游姿势也是"前缀稳定 + append-only"）。
	//
	// 代价（主人在案）：本会话内**新写的记忆**在 system 常驻段看不见；尾部召回指针仍在，
	// 实际可见性损失比"整个记忆系统冻结"小得多。
	//
	// 边界：① 新会话（新 agentId）按最新记忆重新渲染；② 无 agent 上下文的 assemble（宿主
	// 内部调用）按旧行为每次重算；③ 只有**渲染成功**的结果才入缓存（抛错照旧抛、下次重试，
	// 不改 `#isDown()` 的降级语义）；④ 快照有上限（`promptFreezeMax`，超限淘汰最旧键），
	// 长跑进程不累积。
	const frozenSections = new Map();
	function renderRecallSection() {
		return renderPrompt(open().forPrompt(config.promptRecentCount), config.promptMaxChars);
	}
	function recallSectionText(context) {
		if (!config.promptFreezeSystem) return renderRecallSection();
		const agentId = context && context.agent && context.agent.id !== void 0 ? String(context.agent.id) : null;
		if (agentId === null) return renderRecallSection();
		const cached = frozenSections.get(agentId);
		if (cached !== void 0) return cached;
		const text = renderRecallSection();
		if (frozenSections.size >= Math.max(1, config.promptFreezeMax)) {
			const oldest = frozenSections.keys().next();
			if (!oldest.done) frozenSections.delete(oldest.value);
		}
		frozenSections.set(agentId, text);
		return text;
	}
	ctx.systemPrompt.section({
		name: "memory:recall",
		order: config.promptOrder,
		text: recallSectionText
	});
	// FORK-EDIT(2026-09-21): 指针注入 —— 每回合第一个 step 注入一条 ≤800 字召回指针。
	// 语义（方案 §3.4）：先委派下游拿最终决策；被拒绝/信号已中止则不注入；只在 step===1；
	// 全异常捕获（fail-open）——最坏结果 = 不注入，绝不阻塞对话。
	ctx.on("agent/pre-step", async ({ agent, messages, turn, step, signal }, next) => {
		const decision = await next();
		try {
			if (!decision || decision.kind === "reject") return decision;
			if (signal && signal.aborted) return decision;
			if (step !== 1) return decision;
			const query = lastUserText(messages);
			if (!query) return decision;
			const sessionId = agent && agent.id ? String(agent.id) : null;
			const result = await injector.decideWithTimeout({ query, agent, turn, step, sessionId });
			if (result.action !== "inject") return decision;
			return {
				kind: "enter",
				messages: [...decision.messages, createUserMessage({
					content: [{ type: "text", text: result.text }],
					// source 形态写死（方案 §3.4 v4 拍板）：自定义 kind，**不复用 form**（form:'recall' 已被 dsh-session-reference 占用）
					source: {
						kind: SOURCE_KIND,
						version: SOURCE_VERSION,
						items: result.meta.ids,
						chars: result.meta.chars,
						tokens: result.meta.estTokens,
						model: result.meta.model ?? null
					}
				})]
			};
		} catch (error) {
			// fail-open：注入链任何异常都不影响对话（方案 §7）
			try {
				recallLogger.log({ event: "skip", reason: "handler-exception", error: String(error && error.message ? error.message : error) });
			} catch {
				/* 写日志失败也不得影响对话 */
			}
			return decision;
		}
	}, { prepend: true });
	registerTool({
		name: "memory_write",
		description: WRITE_DESCRIPTION,
		parameters: {
			text: {
				type: "string",
				required: true,
				description: "The self-contained fact to remember."
			},
			tags: {
				type: "array",
				description: "Optional labels for later retrieval, e.g. [\"preference\", \"build\"].",
				items: { type: "string" }
			},
			pinned: {
				type: "boolean",
				description: "Always show this memory in context. Reserve it for facts that matter in every session."
			}
		},
		output: {
			schema: {
				type: "object",
				additionalProperties: false,
				properties: {
					id: {
						type: "integer",
						required: true
					},
					tags: {
						type: "string",
						required: true
					},
					pinned: {
						type: "boolean",
						required: true
					}
				}
			},
			render: (_args, value) => [{
				type: "text",
				text: `Stored memory #${value.id}${value.pinned ? " (pinned)" : ""}.`
			}]
		},
		presentCall: (args) => ({
			card: "generic",
			title: "memory_write",
			kind: "edit",
			rawInput: args
		}),
		async execute(args) {
			const text = args.text.trim();
			if (text.length === 0) throw new Error("memory_write: `text` must not be blank");
			if (text.length > config.maxTextChars) throw new Error(`memory_write: \`text\` is ${text.length} chars, over the ${config.maxTextChars} limit`);
			const record = open().write(text, normalizeTags(args.tags ?? []), args.pinned ?? false);
			return {
				id: record.id,
				tags: record.tags,
				pinned: record.pinned
			};
		}
	});
	registerTool({
		name: "memory_search",
		description: SEARCH_DESCRIPTION,
		parameters: {
			query: {
				type: "string",
				required: true,
				description: "Keywords to look for in memory text and tags."
			},
			limit: {
				type: "number",
				description: `Maximum results. Defaults to ${config.searchLimitDefault}.`
			}
		},
		output: {
			schema: {
				type: "object",
				additionalProperties: false,
				properties: { matches: {
					type: "array",
					required: true,
					items: {
						type: "object",
						additionalProperties: false,
						properties: {
							id: {
								type: "integer",
								required: true
							},
							text: {
								type: "string",
								required: true
							},
							tags: {
								type: "string",
								required: true
							},
							pinned: {
								type: "boolean",
								required: true
							}
						}
					}
				} }
			},
			render: (args, value) => [{
				type: "text",
				text: value.matches.length === 0 ? `No memories match ${JSON.stringify(args.query)}.` : value.matches.map((match) => promptLine({
					...match,
					createdAt: 0,
					updatedAt: 0
				})).join("\n")
			}],
			presentationMeta: (_args, value) => ({ count: value.matches.length })
		},
		presentCall: (args) => ({
			card: "generic",
			title: `memory_search ${args.query}`,
			kind: "search"
		}),
		async execute(args) {
			const requested = args.limit ?? config.searchLimitDefault;
			if (!Number.isInteger(requested) || requested < 1) throw new Error(`memory_search: \`limit\` must be an integer >= 1 (got ${requested})`);
			return { matches: open().search(args.query, Math.min(requested, config.searchLimitMax)).map(({ id, text, tags, pinned }) => ({
				id,
				text,
				tags,
				pinned
			})) };
		}
	});
	registerTool({
		name: "memory_forget",
		description: FORGET_DESCRIPTION,
		parameters: { id: {
			type: "integer",
			required: true,
			description: "The memory id to delete."
		} },
		output: {
			schema: {
				type: "object",
				additionalProperties: false,
				properties: {
					id: {
						type: "integer",
						required: true
					},
					forgotten: {
						type: "boolean",
						required: true
					}
				}
			},
			render: (_args, value) => [{
				type: "text",
				text: value.forgotten ? `Forgot memory #${value.id}.` : `No memory #${value.id} to forget.`
			}]
		},
		async execute(args) {
			return {
				id: args.id,
				forgotten: open().forget(args.id)
			};
		}
	});
	// FORK-EDIT(2026-09-21): `memory_get` —— 指针指向的那扇门必须由本包自己开（方案 §3.4 关 B1）。
	// 依据：官方 dsh-memory@0.1.0 只注册 memory_write / memory_search / memory_forget，`memory_get` 零命中。
	// 只读；超 `maxTextChars` 截断并提示；每次调用留一行 `event:"expand"` 日志（展开率统计，方案 §8.2）。
	registerTool({
		name: "memory_get",
		description: "Read one stored memory in full by id. Recall pointers in your context list ids and one-line summaries; call this to expand the ones you need instead of guessing their content. Read-only.",
		parameters: { id: {
			type: "integer",
			required: true,
			description: "The memory id to read, as listed in a recall pointer or returned by memory_search / memory_write."
		} },
		output: {
			schema: {
				type: "object",
				additionalProperties: false,
				properties: {
					id: {
						type: "integer",
						required: true
					},
					text: {
						type: "string",
						required: true
					},
					tags: {
						type: "string",
						required: true
					},
					pinned: {
						type: "boolean",
						required: true
					},
					truncated: {
						type: "boolean",
						required: true
					},
					chars: {
						type: "integer",
						required: true
					}
				}
			},
			render: (_args, value) => [{
				type: "text",
				text: value.text.length > 0 ? (value.truncated ? `${value.text}\n\n(truncated: memory #${value.id} is ${value.chars} chars, showing the first ${value.text.length})` : value.text) : `No memory #${value.id}.`
			}],
			presentationMeta: (_args, value) => ({
				chars: value.chars,
				truncated: value.truncated
			})
		},
		presentCall: (args) => ({
			card: "generic",
			title: `memory_get #${args.id}`,
			kind: "read"
		}),
		async execute(args, exec) {
			const id = Number(args.id);
			if (!Number.isInteger(id) || id < 1) throw new Error(`memory_get: \`id\` must be a positive integer (got ${String(args.id)})`);
			const sessionId = exec && exec.agent && exec.agent.id ? String(exec.agent.id) : null;
			const record = open().get(id);
			if (record === void 0) {
				injector.logExpand({ id, chars: 0, truncated: false, found: false, sessionId });
				return {
					id,
					text: "",
					tags: "",
					pinned: false,
					truncated: false,
					chars: 0
				};
			}
			const full = String(record.text ?? "");
			const truncated = full.length > config.maxTextChars;
			injector.logExpand({ id, chars: full.length, truncated, found: true, sessionId });
			return {
				id,
				text: truncated ? full.slice(0, config.maxTextChars) : full,
				tags: String(record.tags ?? ""),
				pinned: Boolean(record.pinned),
				truncated,
				chars: full.length
			};
		}
	});
}

