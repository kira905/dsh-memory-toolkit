/** Monotonic on-disk schema version; a mismatch rebuilds the derived index. */
const SCHEMA_VERSION = 1;
const SCHEMA = `
  CREATE TABLE IF NOT EXISTS memories (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    text TEXT NOT NULL,
    tags TEXT NOT NULL DEFAULT '',
    pinned INTEGER NOT NULL DEFAULT 0,
    created_at INTEGER NOT NULL,
    updated_at INTEGER NOT NULL
  );
  CREATE INDEX IF NOT EXISTS memories_recent ON memories (updated_at DESC, id DESC);
  CREATE VIRTUAL TABLE IF NOT EXISTS memories_fts
    USING fts5(text, tags, content='memories', content_rowid='id');
  CREATE TRIGGER IF NOT EXISTS memories_ai AFTER INSERT ON memories BEGIN
    INSERT INTO memories_fts (rowid, text, tags) VALUES (new.id, new.text, new.tags);
  END;
  CREATE TRIGGER IF NOT EXISTS memories_ad AFTER DELETE ON memories BEGIN
    INSERT INTO memories_fts (memories_fts, rowid, text, tags) VALUES ('delete', old.id, old.text, old.tags);
  END;
  CREATE TRIGGER IF NOT EXISTS memories_au AFTER UPDATE ON memories BEGIN
    INSERT INTO memories_fts (memories_fts, rowid, text, tags) VALUES ('delete', old.id, old.text, old.tags);
    INSERT INTO memories_fts (rowid, text, tags) VALUES (new.id, new.text, new.tags);
  END;
`;
/**
* Normalize a tag list to the lowercase, deduplicated, space-joined form the
* FTS index stores, so `Foo`, `foo`, and a repeated `foo` all match `foo`.
* @param tags - tags as supplied by the model or config.
* @returns the normalized space-joined list, empty when nothing survives.
*/
function normalizeTags(tags) {
	const seen = /* @__PURE__ */ new Set();
	for (const tag of tags) {
		const normalized = tag.trim().toLowerCase().replaceAll(/\s+/g, "-");
		if (normalized.length > 0) seen.add(normalized);
	}
	return [...seen].join(" ");
}
/**
* Compile a free-text query into an FTS5 MATCH expression. Every token is
* quoted, so FTS5 operators a model happens to type (`OR`, `*`, `-`, `"`) are
* matched literally instead of changing the query's meaning or raising a
* syntax error mid-tool-call.
* @param query - the raw query text.
* @returns the MATCH expression, or undefined when the query has no usable token.
*/
function compileMatch(query) {
	const tokens = query.split(/[^\p{L}\p{N}_]+/u).filter((token) => token.length > 0).map((token) => `"${token}"`);
	return tokens.length > 0 ? tokens.join(" ") : void 0;
}
/** Map one row to the record shape, converting SQLite's integer boolean. */
function toRecord(row) {
	return {
		id: row.id,
		text: row.text,
		tags: row.tags,
		pinned: row.pinned !== 0,
		createdAt: row.created_at,
		updatedAt: row.updated_at
	};
}
/**
* The durable memory store. One instance owns one SQLite connection; `close()`
* is idempotent and runs from the plugin's disposer.
*/
var MemoryStore = class {
	#db;
	#closed = false;
	/** FORK-EDIT(2026-09-21): 库不可用原因（null = 正常）。不可用时**只读接口返回空、写接口抛明确错误**。 */
	#unavailable = null;
	/**
	* Open (creating if absent) the store at `path`, applying the schema.
	* @param path - database file path, or `:memory:` for an ephemeral store.
	*/
	constructor(path) {
		if (path !== ":memory:") mkdirSync(dirname(path), { recursive: true });
		this.openWarnings = [];
		const reason = (e) => (e && e.message ? e.message : String(e));
		// ── FORK-EDIT(2026-09-21): 记忆引擎 v2 · S3b「绝不阻断 DSH 启动」加固 ──────────────────
		// 背景（ROG 真机实测 2026-09-21，证据见 `docs\记忆引擎v2-S3b-交付-20260921.md` §B/C 与 §E2）：
		//   · 库**只读**（只读挂载 / 目录 ACL 拒写）时，上游那行 `PRAGMA user_version = N` 会抛
		//     `unable to open database file` ⇒ 构造函数抛 ⇒ 插件 apply 抛 ⇒ **表结构自检根本跑不到**；
		//   · 库**损坏**（非 SQLite 内容）时，上游的 `SCHEMA` exec 抛 ⇒ 插件 apply 抛 ⇒
		//     实测后果不是"记忆功能没了"，而是 **cordis 整个插件树加载失败**（3090 实例上 10 个
		//     client 插件全部不加载，GUI 侧边栏按钮/看板/面板全消失）—— 实质等于阻断 DSH。
		// 处置（本 fork 的行为差异，只在这两类异常库上生效，正常库上与上游逐字一致）：
		//   ① `journal_mode` / `foreign_keys` / `user_version` 逐个软着陆（连接级设置 + 只写不读的标记）；
		//   ② `DatabaseSync` 打开失败 或 `SCHEMA` 建表失败 ⇒ 收敛为**降级 store**（`#unavailable`）：
		//      构造函数不抛，插件正常注册，只读接口返回空、写接口给明确错误 —— 记忆功能不可用，
		//      但 DSH 与其余插件照常（并在日志留痕，避免静默失效）。
		// ──────────────────────────────────────────────────────────────────────────────────
		const softExec = (label, sql) => {
			try {
				this.#db.exec(sql);
			} catch (e) {
				this.openWarnings.push(`${label}: ${reason(e)}`);
			}
		};
		try {
			this.#db = new DatabaseSync(path);
		} catch (e) {
			this.#db = null;
			this.#unavailable = `打开失败：${reason(e)}`;
		}
		if (this.#db) {
			softExec("journal_mode", "PRAGMA journal_mode = DELETE; -- 2026-09-07 baidu-sync fix: WAL shm/wal files break BaiduSync; DELETE has no shm/wal");
			softExec("foreign_keys", "PRAGMA foreign_keys = ON");
			try {
				this.#db.exec(SCHEMA);
			} catch (e) {
				this.#unavailable = `建表失败：${reason(e)}`;
			}
			softExec("user_version", `PRAGMA user_version = ${SCHEMA_VERSION}`);
		}
		// FORK-EDIT(2026-09-21): 记忆引擎 v2 · S3b —— 表结构自检（方案 §3.8 / §3.9）
		// 幂等补 `owner_user` / `visibility` 两列 + `memories_visibility` 索引。
		// **永不抛**：任何失败只落日志（`<home>/logs/memory-schema.log`）并置 `degraded=true`，
		// 绝不阻断 DSH 启动（§3.8 风险与对策③）；结果挂在 `schemaCheck()` 上供上层判降级。
		// `:memory:` 跳过 —— 临时库没有"既存库迁移"语义，跳过同时保证 fork 与上游在内存库上
		// 逐字一致（`test/regression.mjs` 的同输入同输出对照依赖这一点）。
		if (path === ":memory:") {
			this.schemaCheckResult = {
				ok: true, degraded: false, added: [], present: [], indexCreated: false, statements: [],
				ownerUser: null, ownerSource: null, notes: [], error: null, skipped: "内存库跳过表结构自检"
			};
		} else if (!this.#db) {
			this.schemaCheckResult = {
				ok: false, degraded: true, added: [], present: [], indexCreated: false, statements: [],
				ownerUser: null, ownerSource: null, notes: [], error: this.#unavailable, skipped: null
			};
		} else {
			this.schemaCheckResult = ensureMemoryColumns(this.#db, { dbPath: path });
		}
		// FORK-EDIT(2026-09-21): 打开阶段的异常一律落一行日志（否则"库坏了/只读了"会与"库健康"
		// 看起来一模一样 —— 无人抽检就静默失效）。
		if (path !== ":memory:" && (this.#unavailable || this.openWarnings.length > 0)) {
			writeSchemaLog({ dbPath: path }, {
				event: this.#unavailable ? "open-unavailable" : "open-warning",
				ok: false,
				unavailable: this.#unavailable,
				warnings: this.openWarnings
			});
		}
	}
	/**
	* Store one memory.
	* @param text - the fact to remember.
	* @param tags - normalized tag list.
	* @param pinned - whether it always renders in the prompt section.
	* @returns the new record.
	*/
	write(text, tags, pinned) {
		// FORK-EDIT(2026-09-21): 降级 store（库打不开/建表失败）⇒ 写接口给**明确原因**的错误，
		// 不静默丢弃主人的记忆（上层工具会把这条错误原样带回模型）。
		if (this.#isDown()) throw new Error(`memory: 记忆库不可用（${this.#unavailable}）—— 本次写入未落库`);
		const now = Date.now();
		return toRecord(this.#db.prepare("INSERT INTO memories (text, tags, pinned, created_at, updated_at) VALUES (?, ?, ?, ?, ?) RETURNING *").get(text, tags, pinned ? 1 : 0, now, now));
	}
	/**
	* Full-text search over memory text and tags, best match first.
	* @param query - free-text query; FTS operators in it are matched literally.
	* @param limit - maximum hits to return.
	* @returns the ranked matches, empty when the query has no usable token.
	*/
	search(query, limit) {
		// FORK-EDIT(2026-09-21): 降级 store ⇒ 返回空结果（**绝不抛**：搜索失败不该打断对话回合）
		if (this.#isDown()) return [];
		const match = compileMatch(query);
		if (match === void 0) return [];
		return this.#db.prepare(`
      SELECT m.*, memories_fts.rank AS rank
      FROM memories_fts JOIN memories m ON m.id = memories_fts.rowid
      WHERE memories_fts MATCH ? ORDER BY rank LIMIT ?
    `).all(match, limit).map((row) => ({
			...toRecord(row),
			rank: row.rank ?? 0
		}));
	}
	/**
	* Read one memory in full by id.
	* FORK-EDIT(2026-09-21): `memory_get` 的读取口 —— 读的是本插件的权威库
	* （与 memory_write / memory_search 同一个 `path`），不是召回侧的只读副本连接
	* （方案 §3.4 关 B1：指针指向的那扇门必须由本包自己开，且开的必须是同一间屋）。
	* @param id - the record id.
	* @returns the record, or undefined when absent.
	*/
	get(id) {
		// FORK-EDIT(2026-09-21): 降级 store ⇒ 等同于"没有这条"（**绝不抛**）
		if (this.#isDown()) return void 0;
		const row = this.#db.prepare("SELECT * FROM memories WHERE id = ?").get(Number(id));
		return row === void 0 ? void 0 : toRecord(row);
	}
	/**
	* The memories the prompt section renders: pinned first, then most recently
	* updated, with no record repeated.
	* @param recentCount - how many unpinned recent memories to include.
	* @returns pinned records followed by recent ones.
	*/
	forPrompt(recentCount) {
		// FORK-EDIT(2026-09-21): 降级 store ⇒ 段渲染为空（**最关键的一处**：本方法每轮都被
		// `memory:recall` 段调用，这里抛错会把每一轮对话都带崩，比插件加载失败更糟）
		if (this.#isDown()) return [];
		const pinned = this.#db.prepare("SELECT * FROM memories WHERE pinned = 1 ORDER BY updated_at DESC, id DESC").all();
		const recent = this.#db.prepare("SELECT * FROM memories WHERE pinned = 0 ORDER BY updated_at DESC, id DESC LIMIT ?").all(recentCount);
		return [...pinned, ...recent].map(toRecord);
	}
	/**
	* Delete one memory.
	* @param id - the record id.
	* @returns whether a record was deleted.
	*/
	forget(id) {
		// FORK-EDIT(2026-09-21): 降级 store ⇒ 等同于"没删掉任何东西"（**不谎报成功**）
		if (this.#isDown()) return false;
		return this.#db.prepare("DELETE FROM memories WHERE id = ?").run(id).changes > 0;
	}
	/**
	* Total stored memories.
	* @returns the row count.
	*/
	count() {
		// FORK-EDIT(2026-09-21): 降级 store ⇒ 0 条（**绝不抛**）
		if (this.#isDown()) return 0;
		return this.#db.prepare("SELECT COUNT(*) AS n FROM memories").get().n;
	}
	/**
	* FORK-EDIT(2026-09-21): 库是否**不可用** —— 打不开（没有连接）**或** 建表失败（连接在、但表建不出）。
	* 两者都必须走降级路径：只判"连接是否为 null"会漏掉后者，实测后果是坏库上
	* `search` / 段渲染真去执行 SQL 并抛错（每轮对话都会被带崩），见交付报告 §E-C。
	* @returns {boolean}
	*/
	#isDown() {
		return this.#db === null || this.#unavailable !== null;
	}
	/**
	* FORK-EDIT(2026-09-21): 库是否处于降级（不可用）状态。
	* @returns {boolean} true = 库打不开或建表失败，本 store 只提供空结果/明确错误。
	*/
	isUnavailable() {
		return this.#isDown();
	}
	/**
	* FORK-EDIT(2026-09-21): 库不可用的原因（正常时 null）。
	* @returns {string|null}
	*/
	unavailableReason() {
		return this.#unavailable;
	}
	/**
	* FORK-EDIT(2026-09-21): 启动自检结果（只读快照，方案 §3.8）。
	* `degraded === true` ⇒ 两列没加上（库被锁 / 只读 / 损坏），此时依赖 `owner_user`/`visibility`
	* 的功能必须自我降级，**不许**假设列存在；其余功能照常。
	* @returns {object} {@link ensureMemoryColumns} 的返回值。
	*/
	schemaCheck() {
		return this.schemaCheckResult;
	}
	/**
	* FORK-EDIT(2026-09-21): 打开阶段的软着陆告警（只读库上 `PRAGMA` 写不进去等）。
	* 空数组 = 打开阶段的设置全部生效。
	* @returns {string[]} 形如 `["user_version: unable to open database file"]`。
	*/
	openState() {
		return this.openWarnings ?? [];
	}
	/** Close the connection; idempotent, so plugin disposal and tests may both call it. */
	close() {
		if (this.#closed) return;
		this.#closed = true;
		// FORK-EDIT(2026-09-21): 降级 store（没有连接）也要能安全关闭 —— 否则 disposer 会抛
		try {
			this.#db?.close();
		} catch {
			/* 关闭失败不影响插件卸载 */
		}
	}
};

